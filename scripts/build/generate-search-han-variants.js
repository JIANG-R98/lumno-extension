'use strict';

// Writes src/shared/search/search-han-variants.js: each traditional character and
// the simplified one search reads it as. The pairs come from ICU's Hant-Hans
// transform through macOS Foundation (`osascript -l JavaScript`), applied one
// character at a time, so run this on a Mac.
//
// Only one-to-one pairs inside the Basic Multilingual Plane are kept: search
// folds titles in place, and a highlight range must still point at the same
// characters after folding.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const repoRoot = path.resolve(__dirname, '..', '..');
const outputPath = path.join(repoRoot, 'src/shared/search/search-han-variants.js');

const transformScript = `
ObjC.import('Foundation');
function run() {
  const pairs = [];
  const ranges = [[0x3400, 0x4dbf], [0x4e00, 0x9fff]];
  for (const [from, to] of ranges) {
    for (let code = from; code <= to; code += 1) {
      const character = String.fromCharCode(code);
      const simplified = $.NSString.alloc.initWithString(character)
        .stringByApplyingTransformReverse('Hant-Hans', false);
      if (simplified && simplified.js && simplified.js !== character) {
        pairs.push(character + '\\t' + simplified.js);
      }
    }
  }
  return pairs.join('\\n');
}
`;

const raw = execFileSync('osascript', ['-l', 'JavaScript', '-e', transformScript], {
  encoding: 'utf8',
  maxBuffer: 16 * 1024 * 1024
});
const map = new Map();
raw.split('\n').filter(Boolean).forEach((line) => {
  const [traditional, simplified] = line.split('\t');
  if (traditional.length === 1 && simplified && simplified.length === 1) {
    map.set(traditional, simplified);
  }
});
// Follow chains (薴 → 苧 → 苎) to the final form, and drop pairs that only
// lead back to themselves.
const resolve = (character) => {
  const seen = new Set([character]);
  let current = map.get(character);
  while (map.has(current) && !seen.has(current)) {
    seen.add(current);
    current = map.get(current);
  }
  return seen.has(current) ? null : current;
};
const pairs = Array.from(map.keys())
  .sort()
  .map((traditional) => [traditional, resolve(traditional)])
  .filter(([traditional, simplified]) => simplified && simplified !== traditional && !map.has(simplified));

const lines = [];
for (let i = 0; i < pairs.length; i += 32) {
  lines.push(`  '${pairs.slice(i, i + 32).map((pair) => pair.join('')).join('')}'`);
}
const source = `// Generated by scripts/build/generate-search-han-variants.js from ICU's Hant-Hans
// transform (Unicode License v3, see LICENSE-unicode.txt). Do not edit by hand.
//
// Each traditional character followed by the simplified one search reads it
// as, so "台湾" finds "臺灣" and "臺灣" finds "台湾". ${pairs.length} pairs, one
// character each.
globalThis.LumnoSearchHanVariants = [
${lines.join(',\n')}
].join('');
`;
fs.writeFileSync(outputPath, source);
console.log(`Wrote ${pairs.length} pairs to ${path.relative(repoRoot, outputPath)}`);
